def invalid_cases():
    args = arguments()
    cases = [("metrics", (m.model_dump() for m in args["metrics"]))]
    cases = [("metrics", tuple(cases[0][1])), ("metrics", list(args["metrics"])),
             ("metrics", args["metrics"][::-1]), ("metrics", (args["metrics"][0],) * 2),
             ("basis", "EXPOSED_FIELDS"), ("basis", "INVALID"), ("coverage", {"contributing_count": True}),
             ("coverage", {"unknown": 1})]
    for name in ("slot", "coverage", "input_set"):
        for prefix in ("sl1:", "xc1:", "is1:"):
            cases.append((name, prefix + "a" * 64))
        cases.append((name, "malformed"))
    for stamp in ("2026-01-01T12:00:00.1234567Z", "2026-01-01T12:00:00", "1234", "2026-02-30T12:00:00Z"):
        raw = args["slot"].model_dump(mode="python")
        raw["slot_time"]["at"] = stamp
        cases.append(("slot", raw))
    cases.append(("metrics", (args["metrics"][0].model_copy(update={"value": 1.5}),)))
    cases.append(("coverage", args["coverage"].model_copy(update={"contributing_count": -1})))
    cases.append(("slot", args["slot"].model_copy(update={"series_key": {"kind": "DER"}})))
    cases.append(("input_set", BaseModel.model_construct.__func__(InputSetRef, state="KNOWN_EMPTY", digest=None, delivery=None)))
    raw = args["input_set"].model_dump(mode="python")
    raw["delivery"]["received_timestamp"] = raw["delivery"]["source_timestamp"] - timedelta(seconds=1)
    cases.append(("input_set", raw))
    return cases


